# Build universe
universe = []
def add(rows, tier):
    for r in rows:
        ticker, name, sector, aclass, region = r
        atr = ATR_MULTI.get(aclass, 2.0)
        universe.append({
            "ticker": ticker,
            "name": name,
            "tier": tier,
            "asset_class": aclass,
            "region": region,
            "sector": sector,
            "atr_multi_sl": atr,
            "atr_multi_tp": round(atr * 1.5, 2),
            "score_threshold": 7.5 if tier in ("A","B") else (8.0 if tier=="C" else 9.0),
        })

add(TIER_A, "A")
add(TIER_B, "B")
add(TIER_C, "C")
add(TIER_X, "X")

# Dedupe: Tier X overrides, then B, then A, then C (earlier wins for same ticker)
seen = {}
# Tier X first: blacklist must stick
for u in universe:
    if u["tier"] == "X":
        seen[u["ticker"]] = u
for u in universe:
    if u["ticker"] not in seen:
        seen[u["ticker"]] = u

final = sorted(seen.values(), key=lambda x: (x["tier"], x["region"], x["ticker"]))

FIELDNAMES = ["ticker", "name", "tier", "asset_class", "region", "sector",
              "atr_multi_sl", "atr_multi_tp", "score_threshold"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Build a universe CSV from the tier lists")
    ap.add_argument("--out", default=str(Path(__file__).parent / "universe.generated.csv"),
                    help="Output CSV (default tools/universe.generated.csv)")
    ap.add_argument("--force", action="store_true",
                    help="Allow overwriting the curated tools/universe.csv")
    args = ap.parse_args(argv)

    out = Path(args.out)
    curated = (Path(__file__).parent / "universe.csv").resolve()
    if out.resolve() == curated and not args.force:
        print("Refusing to overwrite the curated tools/universe.csv without --force.",
              file=sys.stderr)
        return 2

    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDNAMES)
        w.writeheader()
        w.writerows(final)

    print(f"Universe built: {len(final)} tickers")
    print(f"  Tier A: {sum(1 for u in final if u['tier']=='A')}")
    print(f"  Tier B: {sum(1 for u in final if u['tier']=='B')}")
    print(f"  Tier C: {sum(1 for u in final if u['tier']=='C')}")
    print(f"  Tier X: {sum(1 for u in final if u['tier']=='X')}")
    from collections import Counter
    print(f"  Regions: {Counter(u['region'] for u in final)}")
    print(f"  Asset classes: {Counter(u['asset_class'] for u in final)}")
    print(f"Saved to: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
